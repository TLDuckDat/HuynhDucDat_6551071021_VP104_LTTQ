CREATE DATABASE QL_ThuVien
GO
USE QL_ThuVien
GO

CREATE TABLE THELOAI(
	MATL  INT PRIMARY KEY IDENTITY,
	TENTL NVARCHAR(100) NOT NULL UNIQUE
)
GO

CREATE TABLE SACH(
	MASACH       INT PRIMARY KEY IDENTITY,
	TENSACH      NVARCHAR(200) NOT NULL,
	TACGIA       NVARCHAR(100) NOT NULL,
	NAMXB        INT NOT NULL,
	SOLUONG      INT NOT NULL DEFAULT 0,
	GIABIA       DECIMAL(18,0) NOT NULL,
	CONKINHDOANH BIT NOT NULL DEFAULT 1,
	MATL         INT NOT NULL,

	CONSTRAINT CK_SACH_NXB    CHECK (NAMXB >= 1900),
	CONSTRAINT CK_SACH_SL     CHECK (SOLUONG >= 0),
	CONSTRAINT CK_SACH_GIABIA CHECK (GIABIA > 0),
	CONSTRAINT FK_SACH_MATL   FOREIGN KEY (MATL) REFERENCES THELOAI(MATL)
)
GO

CREATE TABLE PHIEUMUON(
	MAPM        INT PRIMARY KEY IDENTITY,
	HOTENDOCGIA NVARCHAR(100) NOT NULL,
	NGAYMUON    DATETIME NOT NULL DEFAULT GETDATE(),
	HANTRA      DATETIME NOT NULL,
	DATRA       BIT NOT NULL DEFAULT 0,

	CONSTRAINT CK_PM_HANTRA CHECK (HANTRA > NGAYMUON)
)
GO

CREATE TABLE CHITIETMUON(
	MAPM    INT NOT NULL,
	MASACH  INT NOT NULL,
	SOLUONG INT NOT NULL CHECK (SOLUONG > 0),

	CONSTRAINT PK_CHITIETMUON        PRIMARY KEY (MAPM, MASACH),
	CONSTRAINT FK_CHITIETMUON_MAPM   FOREIGN KEY (MAPM)   REFERENCES PHIEUMUON(MAPM),
	CONSTRAINT FK_CHITIETMUON_MASACH FOREIGN KEY (MASACH) REFERENCES SACH(MASACH)
)
GO